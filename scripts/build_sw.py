"""Write sw.js with a precache list of every file the app needs offline, and a fresh VERSION."""
import os, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = ['./', 'index.html', 'style.css?v=41', 'config.js?v=41', 'mascot.js?v=41', 'engine.js?v=41', 'stickerbook.js?v=41', 'popit.js?v=41', 'games.js?v=41', 'sync.js?v=41', 'app.js?v=41', 'zaineb_cards.json', 'media.json', 'credits.json', 'stickers/stickers.json', 'manifest.webmanifest', 'fonts/fonts.css']
extra = []   # big, lazily-warmed set: card photos and voice clips (cached in the background after the new version is active)
for d in ('fonts', 'img/zouzou3d', 'img/popit', 'icons', 'stickers'):
    p = os.path.join(ROOT, d)
    if os.path.isdir(p): files += [f'{d}/{f}' for f in sorted(os.listdir(p)) if not f.startswith('.') and f != 'fonts.css' and os.path.isfile(os.path.join(p, f))]
for d in ('img', 'audio'):
    p = os.path.join(ROOT, d)
    if os.path.isdir(p): extra += [f'{d}/{f}' for f in sorted(os.listdir(p)) if not f.startswith('.') and os.path.isfile(os.path.join(p, f))]
ver = 'zp-' + time.strftime('%Y%m%d-%H%M')
sw = f"""/* generated by scripts/build_sw.py — offline cache for زينب تلعب وتتعلم */
const VERSION = '{ver}';
const FILES = {files!r};
const EXTRA = {extra!r};
const addAll = async (c, list) => {{ for (let i = 0; i < list.length; i += 12) await Promise.all(list.slice(i, i + 12).map(f => c.add(f).catch(() => null))); }};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(VERSION).then(c => addAll(c, FILES)).then(() => self.skipWaiting()));   // small core: installs in seconds
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('zp-') && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim())
    .then(() => caches.open(VERSION).then(c => addAll(c, EXTRA))));   // then the photos and voice, in the background
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET' || !e.request.url.startsWith(self.location.origin)) return;
  const url = new URL(e.request.url); const isPage = e.request.mode === 'navigate' || url.pathname.endsWith('/') || url.pathname.endsWith('index.html');
  if (isPage) {{   // the entry page: network first when online, so a new version is picked up on the next open; cache when offline
    e.respondWith(fetch(e.request).then(res => {{ if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then(c => c.put('index.html', copy)); }} return res; }})
      .catch(() => caches.match('index.html', {{ ignoreSearch: true }})));
    return;
  }}
  // exact cached copy first; otherwise the network (and remember it); an older copy of a versioned file only when offline
  e.respondWith(caches.match(e.request).then(r => r || fetch(e.request).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); }} return res;
  }}).catch(() => caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || caches.match('index.html')))));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw.replace("'./', ", "'./', "))
print(ver, len(files), 'core files precached +', len(extra), 'warmed after activation')
