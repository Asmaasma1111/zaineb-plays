"""Write sw.js with a precache list of every file the app needs offline, and a fresh VERSION."""
import os, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = ['./', 'index.html', 'style.css?v=6', 'mascot.js?v=6', 'engine.js?v=6', 'app.js?v=6', 'zaineb_cards.json', 'media.json', 'credits.json', 'manifest.webmanifest', 'fonts/fonts.css']
for d in ('fonts', 'img', 'icons', 'audio'):
    p = os.path.join(ROOT, d)
    if os.path.isdir(p): files += [f'{d}/{f}' for f in sorted(os.listdir(p)) if not f.startswith('.') and f != 'fonts.css']
ver = 'zp-' + time.strftime('%Y%m%d-%H%M')
sw = f"""/* generated by scripts/build_sw.py — offline cache for زينب تلعب وتتعلم */
const VERSION = '{ver}';
const FILES = {files!r};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(VERSION).then(async c => {{
    for (let i = 0; i < FILES.length; i += 20) await Promise.all(FILES.slice(i, i + 20).map(f => c.add(f).catch(() => null)));
  }}).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('zp-') && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET' || !e.request.url.startsWith(self.location.origin)) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: false }}).then(r => r || caches.match(e.request, {{ ignoreSearch: true }})).then(r => r || fetch(e.request).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); }} return res;
  }}).catch(() => caches.match('index.html'))));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw.replace("'./', ", "'./', "))
print(ver, len(files), 'files precached')
